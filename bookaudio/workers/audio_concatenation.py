import asyncio
import logging
import traceback
from pathlib import Path

from bookaudio.jobs_repository import JobsRepository
from bookaudio.models import Job, JobType
from bookaudio.tts import concat_files_with_ffmpeg
from bookaudio.workers.protocols import Runnable

logger = logging.getLogger(__name__)


class AudioConcatenationWorker:
    """
    Produces a final file from voice samples generated by TTSWorker.
    """

    def __init__(
        self, parent: Runnable, jobs_repository: JobsRepository, output_dir: Path
    ):
        self.parent = parent
        self.jobs_repository = jobs_repository
        self.output_dir = output_dir

    async def dispatch(self):
        while self.parent.running:
            job_id = await self.jobs_repository.claim_next_job(JobType.GLUE)
            if not job_id:
                await asyncio.sleep(1.0)
                continue
            try:
                await self._process_glue_job(job_id)
            except Exception as exc:
                logger.error(
                    f"Glue job {job_id} failed: {exc}\n{traceback.format_exc()}"
                )
                await self.jobs_repository.fail_job(job_id, str(exc))

    async def _process_glue_job(self, job_id: str):
        data = await self.jobs_repository.get_glue_job_data(job_id)
        if not data:
            return
        _, book, voicer_jobs = data

        def get_audio_file_path(job: Job) -> Path:
            result = job.result
            if not result:
                raise TypeError(f"Job with id {job.id} has no result")
            audio_file = result["audio_file"]
            if type(audio_file) is not str:
                raise TypeError(
                    f"job.result of job with id {job.id} doesn't hold a string "
                    f"in 'audio_file' key: {result}"
                )
            return Path(audio_file)

        part_files = [get_audio_file_path(job) for job in voicer_jobs]
        final_mp3 = self.output_dir / f"audiobook_{book.id}.mp3"

        logger.info(f"Gluing {len(part_files)} audio samples into {final_mp3.name}...")
        await concat_files_with_ffmpeg(final_mp3, part_files)

        await self.jobs_repository.complete_glue_job(
            job_id=job_id,
            book_id=book.id,
            output_filename=final_mp3.name,
        )
        logger.info(f"Book {book.id} successfully completed: {final_mp3.name}")
